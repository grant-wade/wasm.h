typedef struct bench_kernel_t {
    const char* name;
    const char* func; /* export to run, or NULL to run the export named name */
    int32_t arg;
    double ops;         /* operations one run performs */
    int32_t live_nodes; /* list nodes live_heap keeps reachable during the runs */
} bench_kernel_t;

static wasm_error_t bench_host_inc(wasm_module_t* mod, const wasm_value_t* args, uint32_t num_args,
                                   wasm_value_t* results, uint32_t num_results, void* userdata) {
    (void)mod;
    (void)num_args;
    (void)num_results;
    (void)userdata;
    results[0].of.i32 = (int32_t)((uint32_t)args[0].of.i32 + 1u);
    return WASM_OK;
}

/* Replaces the list a global of the module holds with one of nodes structs; returns 0 on failure. */
static int bench_live_heap(wasm_module_t* mod, int32_t nodes) {
    wasm_value_t arg = wasm_i32(nodes);
    wasm_value_t result;

    if (wasm_call(mod, "live_heap", &arg, 1, &result, 1) != WASM_OK) {
        fprintf(stderr, "live_heap failed: %s\n", wasm_runtime_error_message(wasm_module_runtime(mod)));
        return 0;
    }
    return 1;
}

static double bench_now_seconds(void) {
#if defined(CLOCK_MONOTONIC) && !defined(_WIN32)
    struct timespec ts;

    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
#else
    return (double)clock() / (double)CLOCKS_PER_SEC;
#endif
}

int main(int argc, char** argv) {
    static const bench_kernel_t kernels[] = {
        { "loop", NULL, 20000000, 20000000, 0 },
        { "mem", NULL, 10000000, 10000000, 0 },
        { "calls", NULL, 30, 2692537, 0 },
        { "br_table", NULL, 10000000, 10000000, 0 },
        { "call_indirect", NULL, 5000000, 5000000, 0 },
        { "float", NULL, 10000000, 10000000, 0 },
        { "call", NULL, 10000000, 10000000, 0 },
        { "call_ref", NULL, 10000000, 10000000, 0 },
        { "return_call", NULL, 10000000, 10000000, 0 },
        { "host_call", NULL, 10000000, 10000000, 0 },
        { "struct_rw", NULL, 10000000, 10000000, 0 },
        { "struct_alloc", NULL, 10000000, 10000000, 0 },
        { "list", NULL, 1000000, 1000000, 0 },
        { "mem_f64", NULL, 1000000, 1000000, 0 },
        { "array_f64", NULL, 1000000, 1000000, 0 },
        { "array_i8", NULL, 1000000, 1000000, 0 },
        { "cast", NULL, 10000000, 10000000, 0 },
        { "i31", NULL, 10000000, 10000000, 0 },
        { "throw", NULL, 1000000, 1000000, 0 },
        { "rethrow", NULL, 1000000, 1000000, 0 },
        { "throw_deep", NULL, 1000000, 1000000, 0 },
        { "try_table", NULL, 20000000, 20000000, 0 },
        { "generator", NULL, 1000000, 1000000, 0 },
        { "generator_live", "generator", 1000000, 1000000, 500000 },
        { "cont_new", NULL, 1000000, 1000000, 0 },
        { "simd", NULL, 10000000, 10000000, 0 },
        { "simd_mem", NULL, 10000000, 10000000, 0 },
        { "cont_deep", NULL, 1000000, 1000000, 0 },
        { "fibers", NULL, 100000, 100000, 0 },
    };
    int repeats = argc > 1 ? atoi(argv[1]) : 5;
    const char* only = argc > 2 ? argv[2] : NULL;
    wasm_config_t config;
    wasm_runtime_t* rt;
    wasm_module_t* mod;
    double total = 0.0;
    size_t k;

    if (repeats < 1) repeats = 1;
    wasm_config_default(&config);
    config.cont_stack_values = 65536;
    config.cont_call_depth = 16384;
    rt = wasm_runtime_new(wasm_libc_allocator(), &config);
    if (!rt || wasm_runtime_last_error(rt) != WASM_OK) {
        fprintf(stderr, "runtime init failed\n");
        wasm_runtime_free(rt);
        return 1;
    }
    if (wasm_bind_host_func(rt, "env", "inc", "i(i)", bench_host_inc, NULL) != WASM_OK) {
        fprintf(stderr, "bind failed: %s\n", wasm_runtime_error_message(rt));
        wasm_runtime_free(rt);
        return 1;
    }
    mod = wasm_load(rt, kernels_wasm, sizeof(kernels_wasm));
    if (!mod) {
        fprintf(stderr, "load failed: %s\n", wasm_runtime_error_message(rt));
        wasm_runtime_free(rt);
        return 1;
    }

    printf("%-14s %10s %8s %12s\n", "kernel", "best ms", "ns/op", "result");
    for (k = 0; k < sizeof(kernels) / sizeof(kernels[0]); k++) {
        wasm_value_t arg = wasm_i32(kernels[k].arg);
        wasm_value_t result = wasm_i32(0);
        double best = 0.0;
        int r;

        if (only && strcmp(only, kernels[k].name) != 0) continue;
        if (kernels[k].live_nodes > 0 && !bench_live_heap(mod, kernels[k].live_nodes)) {
            wasm_module_free(mod);
            wasm_runtime_free(rt);
            return 1;
        }
        for (r = 0; r < repeats; r++) {
            double start = bench_now_seconds();
            double elapsed;

            if (wasm_call(mod, kernels[k].func ? kernels[k].func : kernels[k].name, &arg, 1, &result, 1) != WASM_OK) {
                fprintf(stderr, "%s failed: %s\n", kernels[k].name, wasm_runtime_error_message(rt));
                wasm_module_free(mod);
                wasm_runtime_free(rt);
                return 1;
            }
            elapsed = bench_now_seconds() - start;
            if (r == 0 || elapsed < best) best = elapsed;
        }
        if (kernels[k].live_nodes > 0 && !bench_live_heap(mod, 0)) {
            wasm_module_free(mod);
            wasm_runtime_free(rt);
            return 1;
        }
        total += best;
        if (result.type == WASM_TYPE_F64)
            printf("%-14s %10.1f %8.2f %12.4g\n", kernels[k].name, best * 1e3, best * 1e9 / kernels[k].ops,
                   result.of.f64);
        else
            printf("%-14s %10.1f %8.2f %12d\n", kernels[k].name, best * 1e3, best * 1e9 / kernels[k].ops,
                   (int)result.of.i32);
    }
    printf("%-14s %10.1f\n", "total", total * 1e3);

    wasm_module_free(mod);
    wasm_runtime_free(rt);
    return 0;
}
