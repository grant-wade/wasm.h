typedef struct bench_kernel_t {
    const char* name;
    int32_t arg;
} bench_kernel_t;

static double bench_now_seconds(void) {
#if defined(CLOCK_MONOTONIC) && !defined(_WIN32)
    struct timespec ts;

    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
#else
    return (double)clock() / (double)CLOCKS_PER_SEC;
#endif
}

int main(int argc, char** argv) {
    static const bench_kernel_t kernels[] = {
        { "loop", 20000000 },
        { "mem", 10000000 },
        { "calls", 30 },
        { "br_table", 10000000 },
        { "call_indirect", 5000000 },
        { "float", 10000000 },
    };
    int repeats = argc > 1 ? atoi(argv[1]) : 5;
    const char* only = argc > 2 ? argv[2] : NULL;
    wasm_runtime_t* rt;
    wasm_module_t* mod;
    double total = 0.0;
    size_t k;

    if (repeats < 1) repeats = 1;
    rt = wasm_runtime_new(NULL);
    if (!rt || wasm_runtime_last_error(rt) != WASM_OK) {
        fprintf(stderr, "runtime init failed\n");
        wasm_runtime_free(rt);
        return 1;
    }
    mod = wasm_load(rt, kernels_wasm, sizeof(kernels_wasm));
    if (!mod) {
        fprintf(stderr, "load failed: %s\n", wasm_runtime_error_message(rt));
        wasm_runtime_free(rt);
        return 1;
    }

    printf("%-14s %10s %12s\n", "kernel", "best ms", "result");
    for (k = 0; k < sizeof(kernels) / sizeof(kernels[0]); k++) {
        wasm_value_t arg = wasm_i32(kernels[k].arg);
        wasm_value_t result = wasm_i32(0);
        double best = 0.0;
        int r;

        if (only && strcmp(only, kernels[k].name) != 0) continue;
        for (r = 0; r < repeats; r++) {
            double start = bench_now_seconds();
            double elapsed;

            if (wasm_call(mod, kernels[k].name, &arg, 1, &result, 1) != WASM_OK) {
                fprintf(stderr, "%s failed: %s\n", kernels[k].name, wasm_runtime_error_message(rt));
                wasm_free_module(mod);
                wasm_runtime_free(rt);
                return 1;
            }
            elapsed = bench_now_seconds() - start;
            if (r == 0 || elapsed < best) best = elapsed;
        }
        total += best;
        if (result.type == WASM_TYPE_F64)
            printf("%-14s %10.1f %12.4g\n", kernels[k].name, best * 1e3, result.of.f64);
        else
            printf("%-14s %10.1f %12d\n", kernels[k].name, best * 1e3, (int)result.of.i32);
    }
    printf("%-14s %10.1f\n", "total", total * 1e3);

    wasm_free_module(mod);
    wasm_runtime_free(rt);
    return 0;
}
