//! Writes Zig bindings for a Wasm module: `wasm2zig <module.wasm> <output.zig>`.

const std = @import("std");
const wasm = @import("wasm");

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 3) {
        std.debug.print("usage: wasm2zig <module.wasm> <output.zig>\n", .{});
        std.process.exit(2);
    }

    const bytes = try std.Io.Dir.cwd().readFileAlloc(io, args[1], gpa, .unlimited);
    defer gpa.free(bytes);
    const rt = try wasm.Runtime.init(gpa, .{});
    defer rt.deinit();
    const compiled = rt.compile(bytes) catch |err| {
        std.debug.print("wasm2zig: {s}: {s} ({s})\n", .{ args[1], rt.errorMessage(), @errorName(err) });
        std.process.exit(1);
    };
    defer compiled.deinit();

    var out: std.Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    try generate(gpa, &out.writer, compiled.info(), std.fs.path.basename(args[1]));
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[2], .data = out.written() });
}

/// Writes an `Exports` struct for `ModuleInfo.resolve`, an `Api` type with a method per export,
/// and an `Imports` namespace of function import types for `wasm.checkHost`.
pub fn generate(gpa: std.mem.Allocator, w: *std.Io.Writer, info: *const wasm.ModuleInfo, source_name: []const u8) !void {
    try w.print("//! Generated by wasm2zig from {s}.\n\nconst wasm = @import(\"wasm\");\n\npub const Exports = struct {{\n", .{source_name});
    var exports = info.exports();
    while (exports.next()) |exp| {
        if (std.mem.indexOfScalar(u8, exp.name, 0) != null) continue;
        switch (exp.kind) {
            .func => {
                try w.print("    {f}: ", .{std.zig.fmtId(exp.name)});
                try writeFuncType(w, info.funcType(exp.index).?);
            },
            .global => try w.print("    {f}: wasm.Global({s})", .{ std.zig.fmtId(exp.name), typeName(info.globalType(exp.index)) }),
            .memory => try w.print("    {f}: wasm.Memory", .{std.zig.fmtId(exp.name)}),
            .table => try w.print("    {f}: wasm.Table", .{std.zig.fmtId(exp.name)}),
            else => continue,
        }
        try w.writeAll(",\n");
    }
    try w.writeAll("};\n\n");
    try writeApi(gpa, w, info);
    try w.writeAll("\npub const Imports = struct {\n");

    var modules: std.ArrayList([]const u8) = .empty;
    defer modules.deinit(gpa);
    var imports = info.imports();
    while (imports.next()) |imp| {
        if (imp.kind != .func) continue;
        for (modules.items) |name| {
            if (std.mem.eql(u8, name, imp.module)) break;
        } else try modules.append(gpa, imp.module);
    }
    for (modules.items) |module_name| {
        try w.print("    pub const {f} = struct {{\n", .{std.zig.fmtId(module_name)});
        for (0..info.importCount()) |i| {
            const imp = info.importAt(@intCast(i));
            if (imp.kind != .func or !std.mem.eql(u8, imp.module, module_name)) continue;
            if (firstImportNamed(info, imp) != i) continue;
            try w.print("        pub const {f} = ", .{std.zig.fmtId(imp.name)});
            try writeFuncType(w, info.typeFunc(imp.type_index).?);
            try w.writeAll(";\n");
        }
        try w.writeAll("    };\n");
    }
    try w.writeAll("};\n");
}

/// Writes `Api(Spec)`, whose methods call `Spec`'s exports with `Spec`'s types.
fn writeApi(gpa: std.mem.Allocator, w: *std.Io.Writer, info: *const wasm.ModuleInfo) !void {
    var names: std.ArrayList([]const u8) = .empty;
    defer names.deinit(gpa);
    var exports = info.exports();
    while (exports.next()) |exp| {
        if (isApiExport(exp)) try names.append(gpa, exp.name);
    }
    const spec = try unusedName(gpa, names.items, "Spec");
    defer gpa.free(spec);
    const self = try unusedName(gpa, names.items, "self");
    defer gpa.free(self);
    const arg = try unusedName(gpa, names.items, "arg");
    defer gpa.free(arg);

    try w.print(
        \\/// `Spec`'s exports bound to one instance, with a method per export. `Spec` is `Exports` or a
        \\/// struct `wasm.checkExports` accepts.
        \\pub fn Api(comptime {[spec]s}: type) type {{
        \\    comptime wasm.checkExports(Exports, {[spec]s});
        \\    return struct {{
        \\        exports: wasm.Bound({[spec]s}),
        \\
    , .{ .spec = spec });
    exports = info.exports();
    while (exports.next()) |exp| {
        if (!isApiExport(exp)) continue;
        const id = std.zig.fmtId(exp.name);
        const name = std.zig.fmtString(exp.name);
        try w.writeAll("\n");
        if (exp.kind != .func) {
            try w.print("        pub fn {f}({s}: @This()) @FieldType(wasm.Bound({s}), \"{f}\") {{\n", .{ id, self, spec, name });
            try w.print("            return {s}.exports.{f};\n        }}\n", .{ self, id });
            continue;
        }
        const params = info.funcType(exp.index).?.params.len;
        try w.print("        pub fn {f}({s}: @This()", .{ id, self });
        for (0..params) |i| try w.print(", {s}{d}: wasm.ExportParam({s}, \"{f}\", {d})", .{ arg, i, spec, name, i });
        try w.print(") wasm.Error!wasm.ExportResult({s}, \"{f}\") {{\n", .{ spec, name });
        try w.print("            return wasm.callExport({s}.exports, \"{f}\", .{{", .{ self, name });
        for (0..params) |i| try w.print("{s} {s}{d}", .{ if (i == 0) "" else ",", arg, i });
        try w.print("{s}}});\n        }}\n", .{if (params == 0) "" else " "});
    }
    try w.writeAll("    };\n}\n");
}

/// Whether `Api` has a method for `exp`.
fn isApiExport(exp: wasm.Export) bool {
    if (std.mem.indexOfScalar(u8, exp.name, 0) != null or std.mem.eql(u8, exp.name, "exports")) return false;
    return switch (exp.kind) {
        .func, .global, .memory, .table => true,
        else => false,
    };
}

/// `base` with underscores appended until no name in `taken` starts with it. Caller frees.
fn unusedName(gpa: std.mem.Allocator, taken: []const []const u8, base: []const u8) ![]u8 {
    var name: std.ArrayList(u8) = .empty;
    errdefer name.deinit(gpa);
    try name.appendSlice(gpa, base);
    while (for (taken) |t| {
        if (std.mem.startsWith(u8, t, name.items)) break true;
    } else false) try name.append(gpa, '_');
    return name.toOwnedSlice(gpa);
}

fn firstImportNamed(info: *const wasm.ModuleInfo, imp: wasm.Import) usize {
    for (0..info.importCount()) |i| {
        const other = info.importAt(@intCast(i));
        if (other.kind == .func and std.mem.eql(u8, other.module, imp.module) and std.mem.eql(u8, other.name, imp.name)) return i;
    }
    unreachable;
}

fn writeFuncType(w: *std.Io.Writer, ft: wasm.FuncType) !void {
    try w.writeAll("fn (");
    for (ft.params, 0..) |param, i| {
        if (i > 0) try w.writeAll(", ");
        try w.writeAll(typeName(param));
    }
    try w.writeAll(") ");
    switch (ft.results.len) {
        0 => try w.writeAll("void"),
        1 => try w.writeAll(typeName(ft.results[0])),
        else => {
            try w.writeAll("struct { ");
            for (ft.results, 0..) |result, i| {
                if (i > 0) try w.writeAll(", ");
                try w.writeAll(typeName(result));
            }
            try w.writeAll(" }");
        },
    }
}

fn typeName(t: wasm.ValType) []const u8 {
    return switch (t) {
        .i32 => "i32",
        .i64 => "i64",
        .f32 => "f32",
        .f64 => "f64",
        .v128 => "wasm.V128",
        .funcref => "wasm.FuncRef",
        .externref => "wasm.ExternRef",
        else => "wasm.Value",
    };
}
