/* Returns what bump(n) returns after updating fields, as wasm_test_field_user_sections does. */
static int64_t wasm_test_field_bump(int32_t* counter, int64_t* total, int16_t step, uint16_t* elems, uint32_t n) {
    uint32_t i;

    for (i = 0; i < n; i++) {
        *counter = (int32_t)((uint32_t)*counter + 1u);
        *total += step;
        elems[i & 3u] = (uint16_t)(elems[i & 3u] + 4u);
    }
    return (int64_t)(uint32_t)*counter + *total + (int64_t)((int32_t)(int16_t)elems[0] + (int32_t)elems[3]);
}

TEST(test_gc_field_ops_read_objects_of_other_and_freed_modules) {
    wasm_config_t config;
    wasm_runtime_t rt;
    wasm_module_t* lib;
    wasm_module_t* user;
    wasm_value_t* held;
    wasm_value_t args[2];
    wasm_value_t result;
    uint16_t elems[4] = { 0x7FFE, 0x7FFE, 0x7FFE, 0x7FFE };
    int32_t counter = 5;
    int64_t total = 7;
    uint32_t round;

    wasm_config_default(&config);
    config.initial_gc_heap_size = 4096;
    wasm_init_config(&rt, &config);
    lib = wasm_test_load_sections(&rt, wasm_test_field_lib_sections, sizeof(wasm_test_field_lib_sections));
    user = wasm_test_load_sections(&rt, wasm_test_field_user_sections, sizeof(wasm_test_field_user_sections));
    CHECK_MSG(t, lib != NULL && user != NULL, "%s", rt.error_msg);
    if (!lib || !user) {
        wasm_module_free(user);
        wasm_module_free(lib);
        wasm_destroy(&rt);
        return;
    }
    args[0] = wasm_i32(5);
    WASM_CHECK_OK(t, wasm_call(lib, "make", args, 1, &result, 1));
    held = wasm_ref_hold(&rt, result);
    args[0] = wasm_i32(0x7FFE);
    WASM_CHECK_OK(t, wasm_call(lib, "make_arr", args, 1, &args[1], 1));
    CHECK(t, held != NULL);
    if (held) args[0] = *held;
    WASM_CHECK_OK(t, wasm_call(user, "init", args, 2, NULL, 0));
    wasm_ref_release(&rt, held);
    for (round = 0; round < 3; round++) {
        int64_t expected = wasm_test_field_bump(&counter, &total, -1, elems, 10);

        if (round == 1) wasm_module_free(lib);
        wasm_gc_collect(&rt);
        args[0] = wasm_i32(10);
        result = wasm_i64(0);
        WASM_CHECK_OK(t, wasm_call(user, "bump", args, 1, &result, 1));
        WASM_CHECK_I64(t, result.of.i64, expected);
    }
    wasm_module_free(user);
    wasm_destroy(&rt);
}

