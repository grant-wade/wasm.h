TEST(test_gc_field_ops_move_every_numeric_kind) {
    static const int32_t words[] = { 0, 1, 0x7F, 0x80, 0xFF, 0x7FFF, 0x8000, 0xFFFF, -1, INT32_MIN, 0x12345678, 0x7FA00001 };
    static const uint64_t doublewords[] = { 0, UINT64_C(0x8000000000000000), UINT64_MAX, UINT64_C(0x123456789ABCDEF0),
                                            UINT64_C(0x7FF4000000000001), UINT64_C(0x3FF0000000000000) };
    static const char* const word_kinds[] = { "i32", "f32" };
    static const char* const doubleword_kinds[] = { "i64", "f64" };
    wasm_runtime_t rt;
    wasm_module_t* m;
    wasm_value_t args[8];
    wasm_value_t results[8];
    uint32_t i;
    uint32_t j;
    uint32_t k;

    wasm_init(&rt);
    m = wasm_test_load_sections(&rt, wasm_test_field_kinds_sections, sizeof(wasm_test_field_kinds_sections));
    CHECK_MSG(t, m != NULL, "%s", rt.error_msg);
    if (!m) {
        wasm_destroy(&rt);
        return;
    }
    for (i = 0; i < COUNTOF(words); i++) {
        uint32_t x = (uint32_t)words[i];

        args[0] = wasm_i32(words[i]);
        WASM_CHECK_OK(t, wasm_call(m, "i8", args, 1, results, 8));
        for (k = 0; k < 8; k += 2) {
            WASM_CHECK_I32(t, results[k].of.i32, (int32_t)(int8_t)(uint8_t)(x & 0xFFu));
            WASM_CHECK_I32(t, results[k + 1].of.i32, (int32_t)(x & 0xFFu));
        }
        WASM_CHECK_OK(t, wasm_call(m, "i16", args, 1, results, 8));
        for (k = 0; k < 8; k += 2) {
            WASM_CHECK_I32(t, results[k].of.i32, (int32_t)(int16_t)(uint16_t)(x & 0xFFFFu));
            WASM_CHECK_I32(t, results[k + 1].of.i32, (int32_t)(x & 0xFFFFu));
        }
        for (j = 0; j < COUNTOF(word_kinds); j++) {
            WASM_CHECK_OK(t, wasm_call(m, word_kinds[j], args, 1, results, 4));
            for (k = 0; k < 4; k++) WASM_CHECK_I32(t, results[k].of.i32, words[i]);
        }
    }
    for (i = 0; i < COUNTOF(doublewords); i++) {
        uint64_t high = doublewords[(i + 1u) % COUNTOF(doublewords)];

        args[0] = wasm_i64((int64_t)doublewords[i]);
        for (j = 0; j < COUNTOF(doubleword_kinds); j++) {
            WASM_CHECK_OK(t, wasm_call(m, doubleword_kinds[j], args, 1, results, 4));
            for (k = 0; k < 4; k++) WASM_CHECK_I64(t, results[k].of.i64, (int64_t)doublewords[i]);
        }
        args[1] = wasm_i64((int64_t)high);
        WASM_CHECK_OK(t, wasm_call(m, "v128", args, 2, results, 8));
        for (k = 0; k < 8; k += 2) {
            WASM_CHECK_I64(t, results[k].of.i64, (int64_t)doublewords[i]);
            WASM_CHECK_I64(t, results[k + 1].of.i64, (int64_t)high);
        }
    }

    args[0] = wasm_i32(0x1FF);
    args[1] = wasm_i32(0x18000);
    args[2] = wasm_i32(INT32_MIN);
    args[3] = wasm_i64(INT64_MIN + 5);
    args[4] = wasm_i32(0x7FA00001);
    args[5] = wasm_i64(INT64_C(0x7FF4000000000001));
    args[6] = wasm_i64(-2);
    args[7] = wasm_i64(INT64_C(0x0123456789ABCDEF));
    WASM_CHECK_OK(t, wasm_call(m, "new_all", args, 8, results, 8));
    WASM_CHECK_I32(t, results[0].of.i32, -1);
    WASM_CHECK_I32(t, results[1].of.i32, 0x8000);
    WASM_CHECK_I32(t, results[2].of.i32, INT32_MIN);
    WASM_CHECK_I64(t, results[3].of.i64, INT64_MIN + 5);
    WASM_CHECK_I32(t, results[4].of.i32, 0x7FA00001);
    WASM_CHECK_I64(t, results[5].of.i64, INT64_C(0x7FF4000000000001));
    WASM_CHECK_I64(t, results[6].of.i64, -2);
    WASM_CHECK_I64(t, results[7].of.i64, INT64_C(0x0123456789ABCDEF));
    WASM_CHECK_OK(t, wasm_call(m, "defaults", NULL, 0, results, 1));
    WASM_CHECK_I64(t, results[0].of.i64, 0);

    args[0] = wasm_i32(-3);
    WASM_CHECK_OK(t, wasm_call(m, "made", args, 1, results, 1));
    for (k = 0; k < 7; k++) {
        const wasm_fieldtype_t* field = wasm_struct_type_field(m, 0, k);
        uint32_t bits = 0xFFFFFFFDu;
        uint64_t wide = 0xFFFFFFFDu;
        wasm_value_t expected;
        wasm_value_t value;

        memset(&expected, 0, sizeof(expected));
        memset(&value, 0xA5, sizeof(value));
        expected.type = field->storage.kind == WASM_STORAGE_PACKED ? WASM_TYPE_I32 : field->storage.of.valtype;
        if (k == 0) expected.of.i32 = 0xFD;
        if (k == 1) expected.of.i32 = 0xFFFD;
        if (k == 2) expected.of.i32 = -3;
        if (k == 3) expected.of.i64 = -3;
        if (k == 4) memcpy(&expected.of.f32, &bits, sizeof(bits));
        if (k == 5) memcpy(&expected.of.f64, &wide, sizeof(wide));
        for (j = 0; k == 6 && j < 16; j += 4) memcpy(expected.of.v128 + j, &bits, sizeof(bits));
        WASM_CHECK_OK(t, wasm_struct_get_field(m, results[0], k, &value));
        CHECK_MSG(t, value.type == expected.type && memcmp(&value.of, &expected.of, sizeof(value.of)) == 0,
                  "field %u reads back as type 0x%X", (unsigned)k, (unsigned)value.type);
    }
    WASM_CHECK_OK(t, wasm_call(m, "made_arr", args, 1, results, 3));
    for (k = 0; k < 3; k++) {
        static const wasm_valtype_t types[] = { WASM_TYPE_I64, WASM_TYPE_V128, WASM_TYPE_I32 };

        for (j = 0; j < 2; j++) {
            wasm_value_t expected;
            wasm_value_t value;
            uint32_t bits = 0xFFFFFFFDu;
            uint32_t lane;

            memset(&expected, 0, sizeof(expected));
            memset(&value, 0xA5, sizeof(value));
            expected.type = types[k];
            if (j == 1 && k == 0) expected.of.i64 = -3;
            for (lane = 0; j == 1 && k == 1 && lane < 16; lane += 4) memcpy(expected.of.v128 + lane, &bits, sizeof(bits));
            if (j == 1 && k == 2) expected.of.i32 = 0xFFFD;
            WASM_CHECK_OK(t, wasm_array_get_elem(m, results[k], j, &value));
            CHECK_MSG(t, value.type == expected.type && memcmp(&value.of, &expected.of, sizeof(value.of)) == 0,
                      "array %u element %u reads back as type 0x%X", (unsigned)k, (unsigned)j, (unsigned)value.type);
        }
    }
    wasm_module_free(m);
    wasm_destroy(&rt);
}

