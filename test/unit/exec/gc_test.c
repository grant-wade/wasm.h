/* Returns whether variant v, br_on_cast_fail if bit 0, from a non-null type if bit 1, and to a nullable type if
 * bit 2, branches on a value that is null if is_null and else matches if matches. */
static int wasm_test_cast_branch_taken(uint32_t v, int is_null, int matches) {
    int result = is_null ? (v & 4u) != 0 : matches;

    return (v & 1u) ? !result : result;
}

/* Returns the ref.test mask of count targets as the mask exports compute it. */
static int32_t wasm_test_cast_mask(int is_null, const int* matches, uint32_t count) {
    uint32_t mask = 0;
    uint32_t k;

    for (k = 0; k < count; k++) {
        if (!is_null && matches[k]) mask |= 1u << k;
        if (is_null || matches[k]) mask |= 1u << (k + 8u);
    }
    return (int32_t)mask;
}

enum { WASM_TEST_ANY_NULL, WASM_TEST_ANY_I31, WASM_TEST_ANY_STRUCT, WASM_TEST_ANY_ARRAY, WASM_TEST_ANY_BOX };

/* Checks the any_mask, any_cast, and any_br exports of m on value x of class cls. */
static void wasm_test_cast_any_value(test_ctx* t, wasm_module_t* m, wasm_value_t x, int cls, const char* what) {
    int matches[6];
    wasm_value_t args[2];
    wasm_value_t results[2];
    uint32_t j;

    matches[0] = cls != WASM_TEST_ANY_NULL;
    matches[1] = cls == WASM_TEST_ANY_I31 || cls == WASM_TEST_ANY_STRUCT || cls == WASM_TEST_ANY_ARRAY;
    matches[2] = cls == WASM_TEST_ANY_I31;
    matches[3] = cls == WASM_TEST_ANY_STRUCT;
    matches[4] = cls == WASM_TEST_ANY_ARRAY;
    matches[5] = 0;
    args[0] = x;
    results[0] = wasm_i32(-1);
    WASM_CHECK_OK(t, wasm_call(m, "any_mask", args, 1, results, 1));
    CHECK_MSG(t, results[0].of.i32 == wasm_test_cast_mask(cls == WASM_TEST_ANY_NULL, matches, 6),
              "any_mask of %s: 0x%x", what, (unsigned)results[0].of.i32);
    for (j = 0; j < 12; j++) {
        int ok = cls == WASM_TEST_ANY_NULL ? j >= 6 : matches[j % 6];
        wasm_error_t err;

        args[1] = wasm_i32((int32_t)j);
        err = wasm_call(m, "any_cast", args, 2, results, 1);
        CHECK_MSG(t, ok ? err == WASM_OK : err == WASM_ERR_TRAP && strcmp(m->rt->error_msg, "cast failure") == 0,
                  "any_cast %u of %s: %s", (unsigned)j, what, wasm_error_string(err));
    }
    for (j = 0; j < 48; j++) {
        if ((j & 2u) && cls == WASM_TEST_ANY_NULL) continue;
        args[1] = wasm_i32((int32_t)j);
        memset(results, 0, sizeof(results));
        WASM_CHECK_OK(t, wasm_call(m, "any_br", args, 2, results, 2));
        CHECK_MSG(t, results[0].of.gc_ref == x.of.gc_ref, "any_br %u of %s passed on a different value", (unsigned)j,
                  what);
        CHECK_MSG(t, results[1].of.i32 == wasm_test_cast_branch_taken(j % 8u, cls == WASM_TEST_ANY_NULL,
                                                                      matches[j / 8u]),
                  "any_br %u of %s: %d", (unsigned)j, what, results[1].of.i32);
    }
}

