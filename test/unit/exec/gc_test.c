TEST(test_gc_casts_match_hierarchies_deeper_than_type_displays) {
    static const uint32_t targets[] = { 0, 1, 31, 62, 63, 64, 65, 69 };
    wasm_runtime_t rt;
    wasm_module_t* mods[2];
    uint32_t i;
    uint32_t k;
    uint32_t j;

    wasm_init(&rt);
    for (i = 0; i < 2; i++) {
        mods[i] = wasm_test_load_sections(&rt, wasm_test_cast_deep_sections, sizeof(wasm_test_cast_deep_sections));
        CHECK_MSG(t, mods[i] != NULL, "%s", rt.error_msg);
    }
    for (k = 0; mods[0] && mods[1] && k < 70; k++) {
        wasm_value_t arg = wasm_i32((int32_t)k);
        wasm_value_t x;
        wasm_value_t* held;
        uint32_t mask = 0;

        for (j = 0; j < COUNTOF(targets); j++) {
            if (k >= targets[j]) mask |= 1u << j;
            if (k == targets[j]) mask |= 1u << (j + 8u);
        }
        WASM_CHECK_OK(t, wasm_call(mods[k & 1u], "make", &arg, 1, &x, 1));
        held = wasm_ref_hold(&rt, x);
        CHECK(t, held != NULL);
        if (!held) break;
        for (i = 0; i < 2; i++) {
            wasm_value_t args[2];
            wasm_value_t result = wasm_i32(-1);

            args[0] = *held;
            WASM_CHECK_OK(t, wasm_call(mods[i], "test_mask", args, 1, &result, 1));
            CHECK_MSG(t, (uint32_t)result.of.i32 == mask, "test_mask of $d%u: 0x%x, not 0x%x", (unsigned)k,
                      (unsigned)result.of.i32, (unsigned)mask);
            for (j = 0; j < COUNTOF(targets); j++) {
                wasm_error_t err;

                args[0] = *held;
                args[1] = wasm_i32((int32_t)j);
                err = wasm_call(mods[i], "cast", args, 2, &result, 1);
                CHECK_MSG(t, k >= targets[j] ? err == WASM_OK : err == WASM_ERR_TRAP && strcmp(rt.error_msg, "cast failure") == 0,
                          "cast of $d%u to $d%u: %s", (unsigned)k, (unsigned)targets[j], wasm_error_string(err));
            }
        }
        wasm_ref_release(&rt, held);
    }
    for (i = 0; i < 2; i++) wasm_module_free(mods[i]);
    wasm_destroy(&rt);
}

